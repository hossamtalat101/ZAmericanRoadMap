// دوال مساعدة للبيانات
function getMonthById(monthId) {
  return learningPlan.months.find((month) => month.id === monthId);
}

function getWeekData(monthId, weekNumber) {
  const month = getMonthById(monthId);
  if (!month) return null;
  return month.weeksData.find((week) => week.week === weekNumber);
}

function getAllWeeks() {
  const allWeeks = [];
  learningPlan.months.forEach((month) => {
    month.weeksData.forEach((week) => {
      allWeeks.push({
        monthId: month.id,
        monthName: month.name,
        weekNumber: week.week,
        weekData: week,
      });
    });
  });
  return allWeeks;
}

